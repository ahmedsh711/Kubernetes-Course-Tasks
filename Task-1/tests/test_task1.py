# 2. LINEAR TESTS — Sequential End-to-End Execution on Live 3-Node Cluster
# ============================================================================
class TestLinearClusterLifecycle:
    def test_linear_01_three_nodes_and_calico_ready(self):
        nodes_out = run_kubectl(["get", "nodes", "-o", "wide"])
        for node_name in ("minikube", "minikube-m02", "minikube-m03"):
            assert re.search(rf"^{node_name}\s+Ready\b", nodes_out, re.M), f"Node {node_name} not Ready"

        calico_pods = run_kubectl(["get", "pods", "-n", "kube-system", "-l", "k8s-app=calico-node"])
        running_calico = len(re.findall(r"1/1\s+Running", calico_pods))
        assert running_calico == 3

    def test_linear_02_deploy_working_and_verify_checks_2_to_8(self):
        run_kubectl(["apply", "-f", str(TASK_DIR / "namespace.yaml")])
        run_kubectl(["apply", "-f", str(TASK_DIR / "deployment.yaml")])
        run_kubectl(["rollout", "status", "deploy/web-deployment", "-n", "webapp", "--timeout=180s"])

        # Check #2: Deployment 3/3
        dep_out = run_kubectl(["get", "deploy", "web-deployment", "-n", "webapp"])
        assert "3/3" in dep_out

        # Check #3: 3 Pods, each 2/2 Running
        pods_out = run_kubectl(["get", "pods", "-n", "webapp", "-l", "app=web"])
        assert len(re.findall(r"2/2\s+Running", pods_out)) == 3

        # Check #4: Container names
        containers = run_kubectl([
            "get", "pods", "-n", "webapp", "-l", "app=web",
            "-o", "jsonpath={.items[0].spec.initContainers[*].name} {.items[0].spec.containers[*].name}",
        ])
        assert containers == "init-done nginx time-updater"

        # Check #5: Init container logs
        init_log = run_kubectl(["logs", "deploy/web-deployment", "-n", "webapp", "-c", "init-done"])
        assert init_log.strip() == "done"

        # Check #6: Sidecar sees nginx master process
        ps_out = run_kubectl(["exec", "deploy/web-deployment", "-n", "webapp", "-c", "time-updater", "--", "ps"])
        assert "nginx: master process" in ps_out

        # Check #7: Time updates over 5 seconds on the same pod
        pod0 = run_kubectl(["get", "pods", "-n", "webapp", "-l", "app=web", "-o", "jsonpath={.items[0].metadata.name}"])
        t1 = run_kubectl(["exec", pod0, "-n", "webapp", "-c", "nginx", "--", "cat", "/usr/share/nginx/html/index.html"])
        time.sleep(5.5)
        t2 = run_kubectl(["exec", pod0, "-n", "webapp", "-c", "nginx", "--", "cat", "/usr/share/nginx/html/index.html"])
        assert "hello in MLOPS MENA COMMUNITY :" in t1
        assert "hello in MLOPS MENA COMMUNITY :" in t2
        assert t1 != t2, f"Expected timestamp to update after 5s, got identical: {t1}"

        # Check #8: No volumes
        vols = run_kubectl(["get", "deploy", "web-deployment", "-n", "webapp", "-o", "jsonpath={.spec.template.spec.volumes}"])
        assert vols == ""

    def test_linear_03_step5_failing_init_and_zero_downtime_http(self):
        run_kubectl(["apply", "-f", str(TASK_DIR / "deployment-failing-init.yaml")])

        fail_pod = None
        for _ in range(20):
            time.sleep(2)
            pods_out = run_kubectl(["get", "pods", "-n", "webapp", "-l", "app=web"])
            m = re.search(r"^(\S+)\s+0/2\s+Init:(?:Error|CrashLoopBackOff)", pods_out, re.M)
            if m:
                fail_pod = m.group(1)
                if "Init:CrashLoopBackOff" in pods_out:
                    break
        assert fail_pod is not None, "New pod did not enter Init:Error / Init:CrashLoopBackOff"

        # Verify the 3 old Pods remain 2/2 Running
        pods_out = run_kubectl(["get", "pods", "-n", "webapp", "-l", "app=web"])
        assert len(re.findall(r"2/2\s+Running", pods_out)) == 3

        # Verify init-done logs and Exit Code: 1
        fail_log = run_kubectl(["logs", fail_pod, "-n", "webapp", "-c", "init-done"])
        assert "init failed" in fail_log
        desc = run_kubectl(["describe", "pod", fail_pod, "-n", "webapp"])
        assert re.search(r"Exit Code:\s*1", desc)

        # Verify live HTTP reachability on localhost:8080 during failing rollout
        pf = subprocess.Popen(
            ["kubectl", "port-forward", "-n", "webapp", "deploy/web-deployment", "18080:80"],
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
        )
        try:
            time.sleep(2.5)
            with urllib.request.urlopen("http://localhost:18080", timeout=5) as resp:
                body = resp.read().decode("utf-8")
                assert resp.status == 200
                assert "hello in MLOPS MENA COMMUNITY :" in body
        finally:
            pf.terminate()
            pf.wait(timeout=5)

    def test_linear_04_step6_fix_recovery(self):
        run_kubectl(["apply", "-f", str(TASK_DIR / "deployment.yaml")])
        run_kubectl(["rollout", "status", "deploy/web-deployment", "-n", "webapp", "--timeout=180s"])

        # rollout status returns once the new pods are ready, but the broken pod from
        # Step 5 can still be terminating for a few seconds. Wait until only 3 remain.
        deadline = time.time() + 90
        names = []
        while time.time() < deadline:
            names = run_kubectl(["get", "pods", "-n", "webapp", "-l", "app=web", "-o", "name"]).splitlines()
            if len(names) == 3:
                break
            time.sleep(2)
        assert len(names) == 3, f"Expected 3 pods after recovery, still have {names}"

        dep_out = run_kubectl(["get", "deploy", "web-deployment", "-n", "webapp"])
        assert re.search(r"web-deployment\s+3/3\s+3\s+3", dep_out)


