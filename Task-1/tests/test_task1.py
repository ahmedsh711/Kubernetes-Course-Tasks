def run_kubectl(args: list[str], timeout: int = 60) -> str:
    res = subprocess.run(
        ["kubectl"] + args,
        capture_output=True,
        text=True,
        encoding="utf-8",
        timeout=timeout,
        check=True,
    )
    return res.stdout.strip()


