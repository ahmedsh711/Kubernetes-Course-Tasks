class TestUnitManifestsAndDocs:
    def test_unit_namespace_manifest(self):
        ns = yaml.safe_load((TASK_DIR / "namespace.yaml").read_text(encoding="utf-8"))
        assert ns["apiVersion"] == "v1"
        assert ns["kind"] == "Namespace"
        assert ns["metadata"]["name"] == "webapp"

    def test_unit_deployment_working_manifest(self):
        dep = yaml.safe_load((TASK_DIR / "deployment.yaml").read_text(encoding="utf-8"))
        assert dep["apiVersion"] == "apps/v1"
        assert dep["kind"] == "Deployment"
        assert dep["metadata"]["name"] == "web-deployment"
        assert dep["metadata"]["namespace"] == "webapp"
        assert dep["spec"]["replicas"] == 3
        assert dep["spec"]["selector"]["matchLabels"] == {"app": "web"}
        assert dep["spec"]["template"]["metadata"]["labels"] == {"app": "web"}

        pod_spec = dep["spec"]["template"]["spec"]
        assert pod_spec.get("shareProcessNamespace") is True
        assert "volumes" not in pod_spec

        init_containers = pod_spec["initContainers"]
        assert len(init_containers) == 1
        assert init_containers[0]["name"] == "init-done"
        assert init_containers[0]["image"] == "busybox:1.36"
        assert init_containers[0]["command"] == ["sh", "-c", "echo done"]

        containers = pod_spec["containers"]
        assert [c["name"] for c in containers] == ["nginx", "time-updater"]

        nginx = containers[0]
        assert nginx["image"] == "nginx:1.27"
        assert nginx["ports"] == [{"containerPort": 80}]
        nginx_script = " ".join(nginx.get("command", []) + nginx.get("args", []))
        assert "hello in MLOPS MENA COMMUNITY :" in nginx_script
        assert "/usr/share/nginx/html/index.html" in nginx_script
        assert "nginx -g 'daemon off;'" in nginx_script

        sidecar = containers[1]
        assert sidecar["image"] == "busybox:1.36"
        caps = sidecar["securityContext"]["capabilities"]["add"]
        assert "SYS_PTRACE" in caps
        sidecar_script = " ".join(sidecar.get("command", []) + sidecar.get("args", []))
        assert "PID=$(pgrep -o nginx)" in sidecar_script
        assert "/proc/$PID/root/usr/share/nginx/html/index.html" in sidecar_script
        assert "sleep 5" in sidecar_script

    def test_unit_failing_init_manifest_exact_diff(self):
        working = yaml.safe_load((TASK_DIR / "deployment.yaml").read_text(encoding="utf-8"))
        failing = yaml.safe_load((TASK_DIR / "deployment-failing-init.yaml").read_text(encoding="utf-8"))

        fail_cmd = failing["spec"]["template"]["spec"]["initContainers"][0]["command"]
        assert fail_cmd == ["sh", "-c", "echo 'init failed'; exit 1"]

        # Mutate only init-done command and verify 100% structural equality elsewhere
        failing["spec"]["template"]["spec"]["initContainers"][0]["command"] = ["sh", "-c", "echo done"]
        assert working == failing

    def test_unit_no_ai_attribution_anywhere(self):
        forbidden = re.compile(r"(Co-Authored-By|Generated with|Generated by|Claude Code|Antigravity)", re.I)
        for p in TASK_DIR.rglob("*"):
            if p.is_file() and p.suffix in {".yaml", ".yml", ".md", ".html", ".ps1", ".py"}:
                if p.name == "test_task1.py":
                    continue
                text = p.read_text(encoding="utf-8", errors="ignore")
                assert not forbidden.search(text), f"Forbidden attribution found in {p}"


