# 3. REGRESSION TESTS — Post-Recovery Invariants, Anti-Drift & Evidence
# ============================================================================
class TestRegressionInvariants:
    def test_regression_no_crashing_pods_remain(self):
        pods_out = run_kubectl(["get", "pods", "-n", "webapp", "-l", "app=web"])
        assert "Init:" not in pods_out
        assert "CrashLoopBackOff" not in pods_out
        assert "Error" not in pods_out
        assert len(re.findall(r"2/2\s+Running", pods_out)) == 3

    def test_regression_zero_sidecar_restarts(self):
        restarts = run_kubectl([
            "get", "pods", "-n", "webapp", "-l", "app=web",
            "-o", "jsonpath={.items[*].status.containerStatuses[*].restartCount}",
        ])
        counts = [int(x) for x in restarts.split()]
        assert all(c == 0 for c in counts), f"Expected 0 container restarts across all pods, got {counts}"

    def test_regression_label_selector_invariance(self):
        wrong_label = run_kubectl(["get", "pods", "-n", "webapp", "-l", "app=web-deployment", "-o", "name"])
        assert wrong_label == ""
        right_label = run_kubectl(["get", "pods", "-n", "webapp", "-l", "app=web", "-o", "name"]).splitlines()
        assert len(right_label) == 3

    def test_regression_evidence_and_screenshots_present(self):
        expected_screenshots = [
            "01-cluster-nodes.png",
            "02-pods-running.png",
            "03-containers-and-init.png",
            "04-sidecar-and-time-update.png",
            "05-browser-time-1.png",
            "06-browser-time-2.png",
            "07-failing-init-rollout.png",
            "08-fixed-rollout.png",
        ]
        for name in expected_screenshots:
            p = SCREENSHOTS_DIR / name
            assert p.exists() and p.stat().st_size > 1000, f"Screenshot missing or empty: {p}"
            assert p.read_bytes()[:8] == b"\x89PNG\r\n\x1a\n", f"Invalid PNG header: {p}"
